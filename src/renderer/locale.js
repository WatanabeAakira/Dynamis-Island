function translateDynamic(text) {
  let match = text.match(/^(\d+) (file|item|aplikasi)$/);
  if (match) {
    const [singular, plural] = match[2] === 'file' ? ['file', 'files']
      : match[2] === 'item' ? ['item', 'items'] : ['app', 'apps'];
    return `${match[1]} ${match[1] === '1' ? singular : plural}`;
  }
  match = text.match(/^(\d+) aplikasi aktif$/);
  if (match) return `${match[1]} active ${match[1] === '1' ? 'app' : 'apps'}`;
  match = text.match(/^(\d+) notifikasi tersimpan\.$/);
  if (match) return `${match[1]} notifications saved.`;
  match = text.match(/^(\d+) pintasan tersimpan\. Aplikasinya sendiri tidak ikut terhapus\.$/);
  if (match) return `${match[1]} shortcuts saved. The apps themselves will not be removed.`;
  match = text.match(/^(\d+) item yang file aslinya sudah tidak ada\.$/);
  if (match) return `${match[1]} items whose original files are missing.`;
  match = text.match(/^(\d+) (referensi|pintasan) dihapus\.$/);
  if (match) return `${match[1]} ${match[2] === 'referensi' ? 'references' : 'shortcuts'} removed.`;
  match = text.match(/^(\d+) belum dibaca · (\d+) total$/);
  if (match) return `${match[1]} unread · ${match[2]} total`;
  match = text.match(/^(\d+) aplikasi dipilih$/);
  if (match) return `${match[1]} ${match[1] === '1' ? 'app' : 'apps'} selected`;
  match = text.match(/^Tambah (\d+)$/);
  if (match) return `Add ${match[1]}`;
  match = text.match(/^Sesi (\d+)$/);
  if (match) return `Session ${match[1]}`;
  match = text.match(/^Sesi hari ini: (\d+)$/);
  if (match) return `Today's sessions: ${match[1]}`;
  match = text.match(/^(\d+) hari lagi$/);
  if (match) return `In ${match[1]} days`;
  match = text.match(/^(\d+) hari lalu$/);
  if (match) return `${match[1]} days ago`;
  match = text.match(/^(\d+) (jam|mnt|menit)$/);
  if (match) return `${match[1]} ${match[2] === 'jam' ? 'hr' : 'min'}`;
  match = text.match(/^(\d+) jam lagi, (.+)$/);
  if (match) return `In ${match[1]} hr, ${match[2]}`;
  match = text.match(/^(\d+) mnt lagi, (.+)$/);
  if (match) return `In ${match[1]} min, ${match[2]}`;
  match = text.match(/^(.+) jam$/);
  if (match) return `${match[1]} hr`;
  match = text.match(/^(.+) mnt$/);
  if (match) return `${match[1]} min`;
  match = text.match(/^Alarm diatur pukul (.+)$/);
  if (match) return `Alarm set for ${match[1]}`;
  match = text.match(/^Timer (\d+) menit dimulai$/);
  if (match) return `Timer started for ${match[1]} minutes`;
  match = text.match(/^Versi (.+)$/);
  if (match) return `Version ${match[1]}`;
  match = text.match(/^Aktifkan alarm (.+)$/);
  if (match) return `Enable alarm ${match[1]}`;
  match = text.match(/^(\d+) aplikasi ditambahkan$/);
  if (match) return `${match[1]} ${match[1] === '1' ? 'app' : 'apps'} added`;
  match = text.match(/^(\d+) item ditambahkan$/);
  if (match) return `${match[1]} ${match[1] === '1' ? 'item' : 'items'} added`;
  match = text.match(/^(\d+) sudah ada$/);
  if (match) return `${match[1]} ${match[1] === '1' ? 'duplicate already exists' : 'duplicates already exist'}`;
  match = text.match(/^(\d+) bukan aplikasi \((.+)\)$/);
  if (match) return `${match[1]} ${match[1] === '1' ? 'is not an app' : 'are not apps'} (${match[2]})`;
  match = text.match(/^(\d+) tidak bisa dibaca$/);
  if (match) return `${match[1]} ${match[1] === '1' ? 'item could not be read' : 'items could not be read'}`;
  match = text.match(/^Tidak ada hasil untuk "(.+)"$/);
  if (match) return `No results for "${match[1]}"`;
  match = text.match(/^Tidak ada aplikasi bernama "(.+)"$/);
  if (match) return `No app named "${match[1]}"`;
  match = text.match(/^(.+) sudah ada$/);
  if (match) return `${match[1]} already exists`;
  match = text.match(/^Awan (\d+)%$/);
  if (match) return `Clouds ${match[1]}%`;
  match = text.match(/^(.+) tersisa$/);
  if (match) return `${match[1]} left`;
  match = text.match(/^Hapus yang hilang \((\d+)\)$/);
  if (match) return `Remove missing items (${match[1]})`;
  match = text.match(/^Buka (.+)$/);
  if (match) return `Open ${match[1]}`;
  match = text.match(/^Cari (.+)$/);
  if (match) return `Search ${match[1]}`;
  match = text.match(/^Hapus (.+)$/);
  if (match) return `Delete ${match[1]}`;
  match = text.match(/^(.+) dihapus$/);
  if (match) return `${match[1]} removed`;
  match = text.match(/^(.+) ditambahkan$/);
  if (match) return `${match[1]} added`;
  match = text.match(/^Berikutnya (.+)$/);
  if (match) return `Next ${match[1]}`;
  match = text.match(/^Gagal: (.+)$/);
  if (match) return `Error: ${match[1]}`;
  return null;
}

export function tr(text, language = currentLanguage) {
  if (language !== 'en') return text;
  return EN[text] || translateDynamic(text) || text;
}

function localizeText(node, language) {
  const previous = node.__localeLocalized;
  const source = previous === undefined || node.data !== previous ? node.data : node.__localeSource;
  const translated = tr(source, language);
  node.__localeSource = source;
  node.__localeLocalized = translated;
  if (node.data !== translated) node.data = translated;
}

function localizeAttributes(el, language) {
  const cache = el.__localeAttributes || (el.__localeAttributes = Object.create(null));
  for (const attr of ['title', 'aria-label', 'placeholder']) {
    const value = el.getAttribute(attr);
    if (value == null) continue;
    const previous = cache[attr];
    const source = !previous || value !== previous.localized ? value : previous.source;
    const translated = tr(source, language);
    cache[attr] = { source, localized: translated };
    if (value !== translated) el.setAttribute(attr, translated);
  }
}

export function localizeTree(root, language = 'id') {
  if (!root) return;
  if (root.nodeType === Node.TEXT_NODE) {
    localizeText(root, language);
    return;
  }
  if (root.nodeType === Node.ELEMENT_NODE) localizeAttributes(root, language);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) localizeText(walker.currentNode, language);
  root.querySelectorAll?.('*').forEach((el) => localizeAttributes(el, language));
}

export function watchLocale(root, getLanguage) {
  setLanguage(getLanguage());
  localizeTree(root, getLanguage());
  const observer = new MutationObserver((mutations) => {
    const language = getLanguage();
    setLanguage(language);
    for (const mutation of mutations) {
      if (mutation.type === 'characterData') localizeText(mutation.target, language);
      else if (mutation.type === 'attributes') localizeAttributes(mutation.target, language);
      else for (const node of mutation.addedNodes) localizeTree(node, language);
    }
  });
  observer.observe(root, {
    subtree: true, childList: true, characterData: true, attributes: true,
    attributeFilter: ['title', 'aria-label', 'placeholder']
  });
  return observer;
}
