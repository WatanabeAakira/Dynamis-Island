const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  setIgnoreMouse: (ignore) => ipcRenderer.send('island:set-ignore', ignore),
  focusWindow: () => ipcRenderer.send('island:focus'),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
  onHelper: (cb) => {
    const handler = (_e, m) => cb(m);
    ipcRenderer.on('helper:msg', handler);
    return () => ipcRenderer.removeListener('helper:msg', handler);
  },
  helperSend: (obj) => ipcRenderer.send('helper:send', obj),
  helperStatus: () => ipcRenderer.invoke('helper:status'),
  getLyrics: (q) => ipcRenderer.invoke('lyrics:get', q),
  reportRect: (r) => ipcRenderer.send('island:rect', r),
  listLyrics: () => ipcRenderer.invoke('lyrics:list'),
  deleteLyrics: (name) => ipcRenderer.invoke('lyrics:delete', name),
  openLyricsDir: () => ipcRenderer.invoke('lyrics:open-dir'),
  importLyricsText: (q, text, name) => ipcRenderer.invoke('lyrics:import-text', q, text, name),
  importLyrics: (q) => ipcRenderer.invoke('lyrics:import', q),
  pickLyricsDir: () => ipcRenderer.invoke('lyrics:pick-dir'),
  audioIcon: (exe) => ipcRenderer.invoke('audio:icon', exe),
  audioOpen: (key) => ipcRenderer.invoke('audio:open', key),
  audioSetOutput: (id) => ipcRenderer.invoke('audio:set-output', id),
  allowFocus: () => ipcRenderer.send('island:allow-focus'),
  weatherLocate: () => ipcRenderer.invoke('weather:locate'),
  weatherSearch: (q) => ipcRenderer.invoke('weather:search', q),
  weatherGet: (p) => ipcRenderer.invoke('weather:get', p),
  releaseFocus: () => ipcRenderer.send('island:release-focus'),
  onHover: (cb) => ipcRenderer.on('island:hover', (_e, inside) => cb(inside)),
  onIslandShown: (cb) => ipcRenderer.on('island:shown', () => cb()),
  pathFor: (file) => webUtils.getPathForFile(file), // path asli file yang di-drop
  onDataChanged: (cb) => ipcRenderer.on('data:changed', (_e, d) => cb(d)),
  trayList: () => ipcRenderer.invoke('tray:list'),
  trayAdd: (paths) => ipcRenderer.invoke('tray:add', paths),
  trayAddDialog: (kind) => ipcRenderer.invoke('tray:add-dialog', kind),
  trayRemove: (id) => ipcRenderer.invoke('tray:remove', id),
  trayPin: (id, v) => ipcRenderer.invoke('tray:pin', id, v),
  trayOpen: (id) => ipcRenderer.invoke('tray:open', id),
  trayReveal: (id) => ipcRenderer.send('tray:reveal', id),
  trayCopy: (id) => ipcRenderer.invoke('tray:copy', id),
  trayClear: () => ipcRenderer.invoke('tray:clear'),
  trayRemoveMissing: () => ipcRenderer.invoke('tray:remove-missing'),
  trayDrag: (id) => ipcRenderer.send('tray:drag', id),
  appsList: () => ipcRenderer.invoke('apps:list'),
  appsAdd: (paths) => ipcRenderer.invoke('apps:add', paths),
  appsAddDialog: () => ipcRenderer.invoke('apps:add-dialog'),
  appsInstalled: (q) => ipcRenderer.invoke('apps:installed', q),
  appsAddInstalled: (paths) => ipcRenderer.invoke('apps:add-installed', paths),
  appsIconForPath: (p) => ipcRenderer.invoke('apps:icon-for-path', p),
  appsRemove: (id) => ipcRenderer.invoke('apps:remove', id),
  appsRename: (id, name) => ipcRenderer.invoke('apps:rename', id, name),
  appsFavorite: (id, v) => ipcRenderer.invoke('apps:favorite', id, v),
  appsReorder: (ids) => ipcRenderer.invoke('apps:reorder', ids),
  appsSetIcon: (id) => ipcRenderer.invoke('apps:set-icon', id),
  appsResetIcon: (id) => ipcRenderer.invoke('apps:reset-icon', id),
  appsLaunch: (id, admin) => ipcRenderer.invoke('apps:launch', id, admin),
  appsReveal: (id) => ipcRenderer.send('apps:reveal', id),
  appsClear: () => ipcRenderer.invoke('apps:clear'),
  winControl: (action) => ipcRenderer.send('settings:win', action),
  notifClear: () => ipcRenderer.send('notif:clear'),
  onNotifCleared: (cb) => ipcRenderer.on('notif:cleared', () => cb()),
  aiHasKey: () => ipcRenderer.invoke('ai:has-key'),
  aiSetKey: (key) => ipcRenderer.invoke('ai:set-key', key),
  aiClearKey: () => ipcRenderer.invoke('ai:clear-key'),
  aiClipboard: () => ipcRenderer.invoke('ai:clipboard'),
  aiChat: (req) => ipcRenderer.send('ai:chat', req),
  aiCancel: (id) => ipcRenderer.send('ai:cancel', id),
  onAiEvent: (cb) => { const h = (_e, ev) => cb(ev); ipcRenderer.on('ai:event', h); return () => ipcRenderer.removeListener('ai:event', h); },
  openSettings: (page) => ipcRenderer.send('settings:open', page),
  onSettings: (cb) => ipcRenderer.on('settings:changed', (_e, s) => cb(s)),
  onSettingsPage: (cb) => ipcRenderer.on('settings:page', (_e, p) => cb(p)),
  onLyricsChanged: (cb) => ipcRenderer.on('lyrics:changed', () => cb()),
  appInfo: () => ipcRenderer.invoke('app:info'),
  openDataDir: () => ipcRenderer.send('app:open-data'),
  quit: () => ipcRenderer.send('app:quit')
});
